const { SQL } = await import("bun");
const db = new SQL(process.env.DATABASE_URL);
const r = await db.unsafe("SELECT indexname, indexdef FROM pg_indexes WHERE tablename='subdistricts'");
for (const x of r) console.log(`  ${x.indexname}: ${x.indexdef}`);
const d = await db.unsafe("SELECT count(*) n, count(DISTINCT code) c FROM subdistricts");
console.log(`  subdistricts: ${d[0].n} rows, ${d[0].c} distinct codes`);
const dup = await db.unsafe("SELECT code, count(*) n, array_agg(name) names FROM subdistricts GROUP BY code HAVING count(*)>1 LIMIT 6");
console.log("  codes used by more than one subdistrict:");
for (const x of dup) console.log(`    code ${x.code}: ${x.n}x  ${JSON.stringify(x.names)}`);
await db.close();