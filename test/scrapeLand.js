const timeout = {
    page: 60000,
};

async function land_init() {
    // set up
    browser = await puppeteer.launch({
        headless: true,
        args: [
            "--no-sandbox", // Required for some environments
            "--disable-setuid-sandbox",
            // "--disable-gpu", // Recommended for some environments
            "--disable-dev-shm-usage", // Recommended for Docker/Linux environments
        ],
        // executablePath: "C:\Program Files (x86)\Google\Chrome\Application\chrome.exe",
    });
    const context = await browser.createBrowserContext();
    page = await context.newPage();
    await page.setUserAgent(
        "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/117.0.0.0 Safari/537.36",
    );
    await page.setExtraHTTPHeaders({
        "Accept-Language": "th-TH,th;q=0.9,en;q=0.8",
        "Upgrade-Insecure-Requests": "1",
    });

    // navigate
    await page.goto("https://www.example.com", { waitUntil: "networkidle2" });
    await page.goto("https://landsmaps.dol.go.th/", {
        waitUntil: "networkidle2",
        timeout: timeout.page,
    });

    // await page.screenshot({ path: "result.png", fullPage: true });   // DEBUG:

    // get token
    const userInfo = await page.evaluate(() => {
        return JSON.parse(sessionStorage.getItem("userinfo"));
    });
    const tokenGET = userInfo?.access_token;
    if (!tokenGET) {
        await browser.close();
        return null;
    } else return tokenGET;
}

// get data from given config -> for 1 times
async function land_get(provinceCode, amphurCode, parcelNo, page) {
    const getservicesearchURL = "https://landsmaps.dol.go.th/apiService/LandsMaps/GetParcelByParcelNo/";
    const apiUrl = `${getservicesearchURL}${provinceCode}/${amphurCode}/${parcelNo}`;

    const data = await page.evaluate(
        async (apiUrl, token) => {
            const res = await fetch(apiUrl, {
                method: "GET",
                credentials: "include",
                headers: {
                    Authorization: `Bearer ${token}`,
                    Accept: "application/json",
                    "Content-Type": "application/json",
                    "X-Requested-With": "XMLHttpRequest",
                },
            });

            const text = await res.text();

            // try JSON parse safely
            try {
                return JSON.parse(text);
            } catch {
                return { __raw: text };
            }
        },
        apiUrl,
        token,
    );

    // error log
    if (data?.__raw) {
        console.log("XHR blocked / not JSON", data.__raw.slice(0, 300));
        return;
    }

    // send back data
    if (data) {
        try {
            const res = data.result[0];

            const item = {
                latlng: [res.parcellat, res.parcellon], // ตำแหน่งที่ดิน
                landprice: res.landprice, // ราคา ต่อตร.วา
                utm: {
                    utm_id: res.utm, // UTM long name
                    utm1: res.utm1, // UTM 1:50000
                    utm1_quad: res.utm2, // UTM 1:50000 quadrant
                    utm_2: res.utm3, // UTM 1:4000
                    utm_sheet: res.utm4, // sheet number
                    utm_scale: res.utmscale, // map scale (1:4000)
                },
                landoffice: {
                    name: res.landoffice,
                    latlng: [res.landofficelat, res.landofficelon],
                },
                link: {
                    land: res.qrcode_link, // link ที่ดิน ในเว็บ landmap
                    survery: res.surveyprice_link, // link เอกสารรังวัด
                },
            };
            return item;
        } catch (e) {
            console.log(`Error: ${e}`);
            return null;
        }
    } else return null;
}

export async function scrapeLand(givenArr) {
    const pageLanddata = [];

    // set up
    token = await land_init();

    for (let i = 0; i < givenArr.length; i++) {
        // get token -> if not, get again (for 10 times)
        for (let tokenCount = 0; tokenCount < 10 && !token; tokenCount++) {
            token = await land_init();
        }

        // there no token -> kill all process
        if (!token) {
            console.error(`Error : can't connect to web and no token`);
            break;
        }

        const piece = givenArr[i];
        const provinceCode = provinceParser(piece.address.city);
        const amphurCode = amphurParser(piece.address.amphur, piece.address.city);

        // skip if there are no
        if (!provinceCode || !amphurCode) {
            console.error(
                `Error : can't find province/amphur for ${piece.address.city} | ${piece.address.amphur}`,
            );
            continue;
        }

        // if not found land data, run again
        let result = null;
        for (let findCount = 0; findCount < 2; findCount++) {
            result = await land_get(provinceCode, amphurCode, piece.address.number, page);
            if (result) {
                pageLanddata.push(result);
                break;
            } else
                console.error(
                    `Error - try again : can't find the paper ${piece.address.city} | ${piece.address.amphur} | ${piece.address.number}`,
                );
        }
        if (!result) {
            console.error(
                `Error : can't find the paper ${piece.address.city} | ${piece.address.amphur} | ${piece.address.number}`,
            );
        }
    }
    
    // console.log(pageLanddata);  // DEBUG:

    // kill all browser
    await browser.close();

    return pageLanddata;
}
